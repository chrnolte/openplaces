"""A bundle's column reference is read from the recipe and the registry.

plans/cheer-pipeline-documentation.md, section 7: the CHEER column page
is generated (flow/delivery_columns.py), so every canonical column must
have a registry description for the page to say what it means. These
tests need no built data.
"""

import pytest

from openplaces.flow import delivery_columns
from openplaces.io.building_imputation import ADJUSTED_COLUMNS
from openplaces.recipe import get_recipe_by_id

#: Delivered recipes whose column reference is published in the docs.
DOCUMENTED_RECIPES = ['US_footprint-cheer-2026']


@pytest.mark.parametrize('recipe_id', DOCUMENTED_RECIPES)
def test_every_canonical_column_is_described(recipe_id):
    rows = delivery_columns.column_rows(get_recipe_by_id(recipe_id))
    assert delivery_columns.undescribed(rows) == []


def test_delivery_written_columns_are_listed():
    names = delivery_columns.canonical_columns(
        get_recipe_by_id('US_footprint-cheer-2026')
    )
    assert set(ADJUSTED_COLUMNS) <= set(names)
    # A cut piece's parent id ships in the evidence file only.
    assert 'footprint_id_parent' not in names


def test_bundle_order_wins_and_sidecars_are_read_from_it():
    recipe = get_recipe_by_id('US_footprint-cheer-2026')
    # A fabricated bundle schema: two declared columns in reverse order,
    # one sidecar, the index and geometry.
    bundle = [
        'n_stories',
        'year_built',
        'year_built_source',
        'footprint_id',
        'geometry',
    ]
    rows = delivery_columns.column_rows(recipe, bundle)
    names = [r.name for r in rows]
    assert names[:3] == ['n_stories', 'year_built', 'footprint_id']
    assert 'geometry' not in names
    by_name = {r.name: r for r in rows}
    assert by_name['year_built'].has_source is True
    assert by_name['n_stories'].has_source is False


@pytest.mark.parametrize(
    ('column', 'expected'),
    [
        ('admin3_id', 'level 3'),
        ('footprint_id', 'Unique id of the footprint'),
        ('structure_value_per_area', 'structure_value divided by area_m2'),
        ('footprint_id_parent', 'the id of the footprint the piece was cut'),
    ],
)
def test_keys_and_ratios_are_described_by_rule(column, expected):
    text, _, _ = delivery_columns.describe(column)
    assert expected in text


@pytest.mark.parametrize(
    ('column', 'source'),
    [
        ('year_built_parcel', 'parcel'),
        ('n_dwellings_nsi', 'nsi'),
        ('occupancy_type_building_nsi_all', 'nsi'),
        ('building_id_nsi', 'nsi'),
        ('city_dwelling_overture', 'overture'),
        ('group_footprint_fema', 'fema'),
        ('roof_shape_building_cheer', 'cheer'),
        ('year_built_source_footprint_ncdps', 'ncdps'),
        ('parcel_id_local', 'parcel'),
        ('structure_value_building_nsi_per_area', 'nsi'),
        ('improvement_value_parcel_whole', 'parcel'),
        ('n_parcels_per_footprint', ''),
        ('n_footprints_per_parcel', ''),
        ('geometry_source_id', ''),
        ('footprint_id_parent', ''),
        ('census_block_id', ''),
    ],
)
def test_evidence_is_grouped_by_the_source_that_supplied_it(column, source):
    assert delivery_columns.evidence_source(column) == source


def test_render_is_stable_without_a_bundle():
    first = delivery_columns.render('US_footprint-cheer-2026')
    assert first == delivery_columns.render('US_footprint-cheer-2026')
    assert first.startswith(
        '.. Generated by python -m openplaces.flow.delivery_columns'
    )


def test_described_columns_link_instead_of_repeating():
    text = delivery_columns.render(
        'US_footprint-cheer-2026',
        described={'year_built': 'cheer_col_year_built'},
        heading_char='-',
    )
    assert 'See :ref:`cheer_col_year_built`.' in text
    assert 'Year building was built' not in text
    assert 'Canonical file\n--------------\n' in text


def test_described_arguments_are_parsed():
    parsed = delivery_columns._parse_described(['lab=a,b', 'other=c'])
    assert parsed == {'a': 'lab', 'b': 'lab', 'c': 'other'}
    with pytest.raises(SystemExit):
        delivery_columns._parse_described(['no-columns'])
